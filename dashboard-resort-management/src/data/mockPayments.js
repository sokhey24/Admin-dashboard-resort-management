export function getMockPayments(options = {}) {
  let data = [...MOCK_PAYMENTS];
  if (options.status && options.status !== 'all') {
    data = data.filter(p => p.status === options.status);
  }
  if (options.search) {
    const q = options.search.toLowerCase();
    data = data.filter(p =>
      p.payment_id?.toLowerCase().includes(q) ||
      p.guest?.name?.toLowerCase().includes(q) ||
      p.source?.toLowerCase().includes(q) ||
      p.payment_method?.toLowerCase().includes(q) ||
      (p.source === 'resort' && p.reference?.booking_code?.toLowerCase().includes(q)) ||
      (p.source === 'restaurant' && p.reference?.order_code?.toLowerCase().includes(q))
    );
  }
  return data;
}

export function getMockPayment(id) {
  return MOCK_PAYMENTS.find(p => p.id === parseInt(id) || p.payment_id === id);
}

export function getMockPaymentStats(payments = MOCK_PAYMENTS) {
  return {
    totalCollected: payments.filter(p => p.status === 'paid').reduce((s, p) => s + (p.breakdown?.paid || p.amount), 0),
    totalPending: payments.filter(p => p.status === 'pending').reduce((s, p) => s + p.amount, 0),
    totalPartial: payments.filter(p => p.status === 'partial').reduce((s, p) => s + (p.breakdown?.balance || 0), 0),
    totalRefunded: payments.filter(p => p.status === 'refunded').reduce((s, p) => s + (p.breakdown?.refund || 0), 0),
    paidCount: payments.filter(p => p.status === 'paid').length,
    pendingCount: payments.filter(p => p.status === 'pending').length,
    partialCount: payments.filter(p => p.status === 'partial').length,
    refundedCount: payments.filter(p => p.status === 'refunded').length,
    failedCount: payments.filter(p => p.status === 'failed').length,
    cancelledCount: payments.filter(p => p.status === 'cancelled').length,
  };
}